import { playerView, projectEvent, resolveFieldBattle, type GameEvent } from '@epochs/engine';
import { GameEventSchema } from '../../../packages/protocol/src/index.js';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import {
  BATTLE_ANNOUNCE_MS,
  BATTLE_IMPACT_MS,
  createGameStore,
  getEventBaseDurationMs,
  type GameStoreApi,
} from '../src/state/game-store.js';
import { createBattleSequenceFixture as fixture } from './fixtures/battle-sequence.js';

beforeEach(() => vi.useFakeTimers());
afterEach(() => vi.useRealTimers());

function nextUntil(store: GameStoreApi, predicate: () => boolean) {
  for (let count = 0; !predicate() && count < 200; count++) vi.advanceTimersToNextTimer();
  expect(predicate()).toBe(true);
}

describe('battle effects generated by the engine', () => {
  it('applies walls, siege and resource balances at their event, without applying raid transfers twice', () => {
    const { initial, final, events } = fixture(0);
    const store = createGameStore();
    store.getState().setPlayerView(playerView(initial, 'P1'));
    store.getState().receiveTransition(playerView(final, 'P1'), events);
    nextUntil(store, () => store.getState().currentEvent?.type === 'WallsModified');
    const walls = events.find((event) => event.type === 'WallsModified')!;
    expect(store.getState().presentationView?.self.walls).toBe(walls.wallsAfter.P1);
    nextUntil(store, () => store.getState().currentEvent?.type === 'SiegeResolved');
    const siege = events.find((event) => event.type === 'SiegeResolved')!;
    expect(store.getState().presentationView?.opponent.walls).toBe(siege.W);
    vi.advanceTimersByTime(BATTLE_ANNOUNCE_MS);
    expect(store.getState().presentationView?.opponent.walls).toBe(siege.wallsAfter);
    expect(store.getState().presentationView?.opponent.cityHp).toBe(siege.cityHpAfter);
    const lastBalance = [...events]
      .reverse()
      .find(
        (event) => event.type === 'ResourcesChanged' && event.player === 'P1' && event.n < siege.n,
      )!;
    if (lastBalance.type === 'ResourcesChanged')
      expect(store.getState().presentationView?.self.resources).toEqual(lastBalance.resources);
    nextUntil(store, () => store.getState().currentEvent?.type === 'RaidResolved');
    const balanceBeforeRaid = store.getState().presentationView?.self.resources;
    vi.advanceTimersByTime(BATTLE_ANNOUNCE_MS);
    expect(store.getState().presentationView?.self.resources).toEqual(balanceBeforeRaid);
    store.getState().skipToEnd();
    store.getState().receiveTransition(playerView(final, 'P1'), events);
    expect(store.getState().presentationView).toBeNull();
    expect(store.getState().isPlaying).toBe(false);
    store.getState().resetStore();
  });

  it('runs six actual melee cycles before marking siege skipped for stalemate', () => {
    const { initial } = fixture();
    initial.catalog = structuredClone(initial.catalog);
    initial.catalog['u1_inf_h']!.atk = 0;
    initial.players.P1.units = [initial.players.P1.units[0]!];
    const events: GameEvent[] = [];
    resolveFieldBattle(initial, events);
    const store = createGameStore();
    store.getState().enqueueEvents(events);
    vi.runAllTimers();
    const cycles = store
      .getState()
      .battleLog.filter(
        (entry) =>
          entry.event.type === 'BattlePhaseResolved' && entry.event.phase === 'phase3_melee',
      );
    expect(cycles).toHaveLength(6);
    expect(store.getState().skippedBattleStages['4']).toBe('Nessun vincitore: stallo');
    expect(store.getState().scannedBattleStages).toEqual(['1', '2A', '2B', '3']);
    store.getState().enqueueEvents([{ n: events.at(-1)!.n + 1, type: 'BattleStarted', era: 2 }]);
    expect(store.getState().scannedBattleStages).toEqual([]);
    store.getState().resetStore();
  });
  it.each(['P1', 'P2'] as const)(
    'keeps the correct era, buffs and nonlethal HP for %s, logging only at impact',
    (viewer) => {
      const { initial, final, events } = fixture();
      const store = createGameStore();
      store.getState().setPlayerView(playerView(initial, viewer));
      store.getState().receiveTransition(
        playerView(final, viewer),
        events.map((event) => projectEvent(event, viewer)),
      );
      expect(store.getState().view?.era).toBe(2);
      expect(store.getState().presentationView?.era).toBe(1);
      nextUntil(store, () => store.getState().currentEvent?.type === 'BattlePhaseResolved');
      expect(store.getState().playbackMoment).toBe('announce');
      expect(
        store.getState().playbackUnits.P1.find((unit) => unit.cardId === 'u1_arc_l')?.atkMod,
      ).toBe(2);
      expect(store.getState().playbackUnits.P2[0]?.hp).toBe(5);
      const before = store.getState().battleLog.length;
      store.getState().pausePlayback();
      vi.advanceTimersByTime(10_000);
      expect(store.getState().battleLog).toHaveLength(before);
      store.getState().resumePlayback();
      vi.advanceTimersByTime(BATTLE_ANNOUNCE_MS);
      expect(store.getState().playbackUnits.P2[0]?.hp).toBe(1);
      expect(store.getState().battleLog).toHaveLength(before + 1);
      expect(store.getState().battleLog.at(-1)?.details?.join(' ')).toContain('HP 5 → 1');
      expect(store.getState().presentationView?.era).toBe(1);
      vi.runAllTimers();
      expect(store.getState().presentationView).toBeNull();
      expect(store.getState().view).toEqual(playerView(final, viewer));
      expect(store.getState().battleLog).toHaveLength(
        events.filter((event) => projectEvent(event, viewer) !== null).length,
      );
      store.getState().resetStore();
    },
  );

  it.each(['announce', 'impact', 'result'] as const)(
    'skip during %s produces the same log and final state as complete playback',
    (moment) => {
      const { initial, final, events } = fixture();
      const normal = createGameStore();
      const skipped = createGameStore();
      for (const store of [normal, skipped]) {
        store.getState().setPlayerView(playerView(initial, 'P1'));
        store.getState().receiveTransition(playerView(final, 'P1'), events);
      }
      nextUntil(
        skipped,
        () =>
          skipped.getState().currentEvent?.type === 'BattlePhaseResolved' &&
          skipped.getState().playbackMoment === moment,
      );
      skipped.getState().skipToEnd();
      vi.runAllTimers();
      expect(skipped.getState().battleLog).toEqual(normal.getState().battleLog);
      expect(skipped.getState().view).toEqual(normal.getState().view);
      expect(skipped.getState().playbackUnits).toEqual(normal.getState().playbackUnits);
      expect(skipped.getState().skippedBattleStages).toEqual(normal.getState().skippedBattleStages);
      normal.getState().resetStore();
      skipped.getState().resetStore();
    },
  );

  it('keeps simultaneous casualties visible at impact and removes them together for the result', () => {
    const { initial } = fixture();
    initial.players.P1.units = [initial.players.P1.units[0]!];
    initial.players.P1.units[0]!.hp = 2;
    initial.players.P2.units[0]!.hp = 2;
    const events: GameEvent[] = [];
    resolveFieldBattle(initial, events);
    const store = createGameStore();
    store.getState().enqueueEvents(events);
    nextUntil(store, () => {
      const event = store.getState().currentEvent;
      return event?.type === 'BattlePhaseResolved' && event.phase === 'phase3_melee';
    });
    vi.advanceTimersByTime(BATTLE_ANNOUNCE_MS);
    expect(store.getState().playbackUnits.P1[0]?.hp).toBe(0);
    expect(store.getState().playbackUnits.P2[0]?.hp).toBe(0);
    vi.advanceTimersByTime(BATTLE_IMPACT_MS);
    expect(store.getState().playbackUnits).toEqual({ P1: [], P2: [] });
    vi.runAllTimers();
    expect(store.getState().skippedBattleStages['4']).toBe('Annientamento reciproco');
    store.getState().resetStore();
  });

  it('roundtrips enriched public events without shared references and accepts legacy payloads', () => {
    const { events } = fixture();
    for (const event of events) expect(GameEventSchema.parse(event)).toEqual(event);
    const start = events.find((event) => event.type === 'BattleStarted')!;
    const projected = projectEvent(start, 'P2');
    expect(projected).toEqual(start);
    expect(projected).not.toBe(start);
    if (start.type === 'BattleStarted' && projected?.type === 'BattleStarted') {
      expect(projected.units).not.toBe(start.units);
      expect(GameEventSchema.parse({ n: start.n, type: 'BattleStarted', era: 1 })).toBeDefined();
    }
    const phase = events.find((event) => event.type === 'BattlePhaseResolved');
    if (phase?.type === 'BattlePhaseResolved') {
      expect(phase.contributions?.P1[0]?.totalDamage).toBe(4);
      const legacy = { ...phase };
      delete legacy.contributions;
      expect(GameEventSchema.parse(legacy)).toEqual(legacy);
    }
  });

  it('retains queued playback on updates and explicitly stops on a resync without event history', () => {
    const { initial, final, events } = fixture();
    const store = createGameStore();
    store.getState().setPlayerView(playerView(initial, 'P1'));
    const target = playerView(final, 'P1');
    store.getState().receiveTransition(target, events);
    store.getState().pausePlayback();
    const lastN = events.at(-1)!.n;
    store
      .getState()
      .receiveTransition({ ...target, stateVersion: target.stateVersion + 1 }, [
        { n: lastN + 1, type: 'PlayerPassed', player: 'P1', era: 2, cycle: 1, reason: 'chosen' },
      ]);
    expect(store.getState().presentationView?.era).toBe(1);
    expect(store.getState().queue.at(-1)?.n).toBe(lastN + 1);
    store.getState().receiveTransition(target, [], { resync: true });
    expect(store.getState().isPlaying).toBe(false);
    expect(store.getState().queue).toEqual([]);
    expect(store.getState().presentationView).toBeNull();
    expect(store.getState().playbackNotice).toContain('riallineata');
    store.getState().resetStore();
  });

  it('resets phase status on the next battle and explains early termination', () => {
    const { initial } = fixture();
    initial.players.P2.units = [];
    const events: GameEvent[] = [];
    resolveFieldBattle(initial, events);
    const store = createGameStore();
    store.getState().enqueueEvents(events);
    nextUntil(store, () => store.getState().currentEvent?.type === 'BattleOutcome');
    expect(store.getState().activeBattleStage).toBe('Esito campale');
    vi.runAllTimers();
    expect(store.getState().activeBattleStage).toBeNull();
    expect(store.getState().skippedBattleStages['1']).toBe('Battaglia già conclusa');
    expect(store.getState().scannedBattleStages).toEqual([]);
    store.getState().enqueueEvents([{ n: events.at(-1)!.n + 1, type: 'BattleStarted', era: 2 }]);
    expect(store.getState().skippedBattleStages).toEqual({});
    expect(store.getState().battleEra).toBe(2);
    store.getState().resetStore();
  });

  it('preserves elapsed time when pausing and changing speed', () => {
    const store = createGameStore();
    const event: GameEvent = {
      n: 1,
      type: 'BattlePhaseResolved',
      era: 1,
      phase: 'phase1_volley',
      damageDealt: { P1: 0, P2: 0 },
      assignments: { P1: [], P2: [] },
      casualties: { P1: [], P2: [] },
    };
    store.getState().enqueueEvents([event]);
    vi.advanceTimersByTime(250);
    store.getState().pausePlayback();
    store.getState().setPlaybackSpeed(2);
    vi.advanceTimersByTime(5000);
    store.getState().resumePlayback();
    vi.advanceTimersByTime((BATTLE_ANNOUNCE_MS - 250) / 2 - 1);
    expect(store.getState().battleLog).toHaveLength(0);
    vi.advanceTimersByTime(1);
    expect(store.getState().battleLog).toHaveLength(1);
    expect(getEventBaseDurationMs(event)).toBeGreaterThan(BATTLE_ANNOUNCE_MS);
    store.getState().resetStore();
  });
});
